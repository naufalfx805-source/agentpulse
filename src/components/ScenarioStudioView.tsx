'use client';

import React, { useState } from 'react';
import {
  Cpu,
  Plus,
  Play,
  CheckCircle2,
  AlertTriangle,
  Code2,
  Filter,
  Check,
  X,
  FileText,
} from 'lucide-react';
import { TestScenario } from '../types/agent';
import { validateNewScenario } from '../lib/scenarioValidation.mjs';

interface ScenarioStudioViewProps {
  scenarios: TestScenario[];
  onAddScenario: (scenario: TestScenario) => void;
}

export const ScenarioStudioView: React.FC<ScenarioStudioViewProps> = ({
  scenarios,
  onAddScenario,
}) => {
  const [filter, setFilter] = useState<string>('all');
  const [showAddModal, setShowAddModal] = useState(false);
  const [runningScenarioId, setRunningScenarioId] = useState<string | null>(null);

  // New scenario form states
  const [title, setTitle] = useState('');
  const [category, setCategory] = useState<'e2e' | 'api' | 'security' | 'regression'>('api');
  const [targetPath, setTargetPath] = useState('');
  const [expectedStatus, setExpectedStatus] = useState('200');
  const [formError, setFormError] = useState<string | null>(null);

  const filteredScenarios = scenarios.filter((s) => {
    if (filter === 'all') return true;
    return s.category === filter;
  });

  const handleCreate = (e: React.FormEvent<HTMLFormElement>) => {
    e.preventDefault();
    // Validate what is actually in the fields. Autofill, browser extensions and
    // scripted input can change a field without firing onChange, which would
    // leave the React state stale (e.g. still "200" after the field was cleared).
    const form = new FormData(e.currentTarget);
    const result = validateNewScenario({
      title: String(form.get('title') ?? ''),
      targetPath: String(form.get('targetPath') ?? ''),
      expectedStatus: String(form.get('expectedStatus') ?? ''),
    });
    if ('error' in result) {
      setFormError(result.error);
      return;
    }
    const { value } = result;

    const newScenario: TestScenario = {
      id: `ts-${Date.now().toString().slice(-4)}`,
      title: value.title,
      category,
      targetPath: value.targetPath,
      expectedStatus: value.expectedStatus,
      assertions: [
        { field: 'response.status', operator: 'equals', expected: String(value.expectedStatus) },
        { field: 'latency', operator: 'less_than', expected: '1000' },
      ],
      lastStatus: 'passed',
      durationMs: Math.floor(Math.random() * 300) + 150,
      flakinessScore: 0.0,
      description: `Custom scenario created for path ${value.targetPath}.`,
    };

    onAddScenario(newScenario);
    setTitle('');
    setTargetPath('');
    setFormError(null);
    setShowAddModal(false);
  };

  const handleSimulateRun = (id: string) => {
    setRunningScenarioId(id);
    setTimeout(() => {
      setRunningScenarioId(null);
    }, 1200);
  };

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 p-6 rounded-2xl border border-slate-800 bg-slate-900/60 backdrop-blur-md">
        <div>
          <h1 className="text-xl font-bold text-slate-100 flex items-center space-x-2">
            <Cpu className="w-5 h-5 text-emerald-400" />
            <span>TestSprite 3.0 Scenario Repository</span>
          </h1>
          <p className="text-xs text-slate-400 mt-1">
            Automated test definitions generated by TestSprite portal agents. Scenarios run automatically on every pull request.
          </p>
        </div>
        <div className="flex items-center space-x-3">
          <button
            onClick={() => setShowAddModal(true)}
            className="flex items-center space-x-2 px-4 py-2 rounded-xl bg-gradient-to-r from-emerald-600 to-teal-600 hover:from-emerald-500 hover:to-teal-500 text-white font-semibold text-sm shadow-lg shadow-emerald-500/20 transition-all"
          >
            <Plus className="w-4 h-4" />
            <span>New Test Scenario</span>
          </button>
        </div>
      </div>

      {/* Filter Tabs */}
      <div className="flex items-center space-x-2 overflow-x-auto pb-1">
        {['all', 'e2e', 'api', 'security', 'regression'].map((cat) => (
          <button
            key={cat}
            onClick={() => setFilter(cat)}
            className={`px-3 py-1.5 rounded-lg text-xs font-semibold uppercase tracking-wider transition-all ${
              filter === cat
                ? 'bg-emerald-500/20 text-emerald-400 border border-emerald-500/30'
                : 'text-slate-400 hover:bg-slate-800/60 hover:text-slate-200'
            }`}
          >
            {cat}
          </button>
        ))}
      </div>

      {/* Scenarios Grid */}
      <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
        {filteredScenarios.map((scenario) => {
          const isRunning = runningScenarioId === scenario.id;
          return (
            <div
              key={scenario.id}
              className="rounded-xl border border-slate-800 bg-slate-900/50 p-5 space-y-4 hover:border-slate-700 transition-all"
            >
              <div className="flex items-start justify-between">
                <div>
                  <div className="flex items-center space-x-2">
                    <span className="font-bold text-slate-200 text-sm">{scenario.title}</span>
                    <span className="px-2 py-0.5 rounded text-[10px] font-mono uppercase bg-slate-800 text-slate-400">
                      {scenario.category}
                    </span>
                  </div>
                  <p className="text-xs text-slate-400 mt-1 leading-relaxed">
                    {scenario.description}
                  </p>
                </div>
                <button
                  onClick={() => handleSimulateRun(scenario.id)}
                  disabled={isRunning}
                  className="p-2 rounded-lg bg-slate-800 hover:bg-slate-700 text-emerald-400 transition-colors"
                  title="Run Scenario"
                >
                  <Play className={`w-4 h-4 ${isRunning ? 'animate-spin' : ''}`} />
                </button>
              </div>

              {/* Path & Assertions */}
              <div className="space-y-2 pt-2 border-t border-slate-800/80">
                <div className="flex items-center justify-between text-xs font-mono">
                  <span className="text-slate-500">Target Endpoint:</span>
                  <span className="text-emerald-400 bg-slate-950 px-2 py-0.5 rounded border border-slate-800">
                    {scenario.targetPath}
                  </span>
                </div>
                <div className="space-y-1">
                  <div className="text-[11px] font-semibold text-slate-400 uppercase tracking-wider">
                    Defined Assertions ({scenario.assertions.length})
                  </div>
                  {scenario.assertions.map((a, i) => (
                    <div
                      key={i}
                      className="flex items-center justify-between text-[11px] font-mono text-slate-300 bg-slate-950/60 px-2.5 py-1 rounded border border-slate-850"
                    >
                      <span className="text-slate-400">{a.field}</span>
                      <span className="text-cyan-400 font-semibold">{a.operator}</span>
                      <span className="text-emerald-400">{a.expected}</span>
                    </div>
                  ))}
                </div>
              </div>

              {/* Status bar */}
              <div className="flex items-center justify-between pt-2 border-t border-slate-800/80 text-xs">
                <span className="flex items-center space-x-1.5 text-emerald-400 font-medium">
                  <CheckCircle2 className="w-4 h-4" />
                  <span>{isRunning ? 'Evaluating...' : 'Verified by TestSprite 3.0'}</span>
                </span>
                <span className="text-slate-500 font-mono">
                  {scenario.durationMs}ms • 0% flakiness
                </span>
              </div>
            </div>
          );
        })}
      </div>

      {/* Modal: Create Scenario */}
      {showAddModal && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-950/80 backdrop-blur-sm">
          <div className="w-full max-w-lg rounded-2xl border border-slate-800 bg-slate-900 p-6 space-y-6 shadow-2xl">
            <div className="flex items-center justify-between">
              <h2 className="text-lg font-bold text-slate-100 flex items-center space-x-2">
                <Plus className="w-5 h-5 text-emerald-400" />
                <span>Create Test Scenario</span>
              </h2>
              <button
                onClick={() => setShowAddModal(false)}
                className="p-1 rounded-lg text-slate-400 hover:text-slate-200"
              >
                <X className="w-5 h-5" />
              </button>
            </div>

            {formError && (
              <div className="p-3 rounded-lg bg-rose-500/10 border border-rose-500/20 text-rose-300 text-xs flex items-center space-x-2">
                <AlertTriangle className="w-4 h-4 flex-shrink-0" />
                <span>{formError}</span>
              </div>
            )}

            <form onSubmit={handleCreate} className="space-y-4">
              <div>
                <label className="block text-xs font-medium text-slate-300 mb-1">
                  Scenario Title
                </label>
                <input
                  type="text"
                  name="title"
                  placeholder="e.g. Verify Token Budget Guard On Large Request"
                  value={title}
                  onChange={(e) => setTitle(e.target.value)}
                  className="w-full bg-slate-950 border border-slate-800 rounded-lg px-3 py-2 text-sm text-slate-200 focus:outline-none focus:border-emerald-500"
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-xs font-medium text-slate-300 mb-1">
                    Category
                  </label>
                  <select
                    value={category}
                    onChange={(e) => setCategory(e.target.value as any)}
                    className="w-full bg-slate-950 border border-slate-800 rounded-lg px-3 py-2 text-sm text-slate-200 focus:outline-none focus:border-emerald-500"
                  >
                    <option value="api">API Endpoint</option>
                    <option value="e2e">Headed E2E</option>
                    <option value="security">Security Guard</option>
                    <option value="regression">Regression Gate</option>
                  </select>
                </div>
                <div>
                  <label className="block text-xs font-medium text-slate-300 mb-1">
                    Expected HTTP Status
                  </label>
                  <input
                    type="number"
                    name="expectedStatus"
                    value={expectedStatus}
                    onChange={(e) => setExpectedStatus(e.target.value)}
                    className="w-full bg-slate-950 border border-slate-800 rounded-lg px-3 py-2 text-sm text-slate-200 focus:outline-none focus:border-emerald-500"
                  />
                </div>
              </div>

              <div>
                <label className="block text-xs font-medium text-slate-300 mb-1">
                  Target Endpoint Path
                </label>
                <input
                  type="text"
                  name="targetPath"
                  placeholder="/api/v1/verify/endpoint"
                  value={targetPath}
                  onChange={(e) => setTargetPath(e.target.value)}
                  className="w-full bg-slate-950 border border-slate-800 rounded-lg px-3 py-2 text-sm text-slate-200 font-mono focus:outline-none focus:border-emerald-500"
                />
              </div>

              <div className="pt-4 flex justify-end space-x-3">
                <button
                  type="button"
                  onClick={() => setShowAddModal(false)}
                  className="px-4 py-2 rounded-lg text-sm text-slate-400 hover:text-slate-200"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  className="px-4 py-2 rounded-lg text-sm font-semibold bg-emerald-600 hover:bg-emerald-500 text-white transition-colors"
                >
                  Save Scenario
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};
